"""Migrations de schéma, versionnées et explicites.

## Le défaut que ce module corrige

Le schéma était construit par `init_db()`, appelée **à l'import de `main`**.
Importer le module suffisait donc à migrer une base de production. Ce n'est pas
une hypothèse : c'est arrivé deux fois, en Phase 30 et en Phase 37.

Une migration est une opération d'exploitation. Elle se déclenche par une
commande, se journalise, et se refuse quand elle n'est pas voulue.

## Stratégie de baseline

Le schéma n'avait pas d'historique versionné : il était le résultat cumulatif
d'`init_db` et de `migrate_schema`. Reconstituer après coup une suite de
migrations qui n'a jamais existé aurait produit un historique faux, et des
migrations que personne n'a jamais exécutées dans cet ordre.

La version 1 est donc **l'état complet à la fin de la Phase 37**, tel que le
code le produisait. Les migrations suivantes s'ajoutent normalement, en
déposant un fichier `NNNN_nom.sql` dans `migrations/`.

## Les cinq cas, et comment chacun est reconnu

| Cas | Détection | Action |
| --- | --- | --- |
| A. base vide | ni `schema_migrations` ni table du noyau | applique tout |
| B. base SQLite historique | pas de `schema_migrations`, noyau présent | adoption |
| C. schéma Phase 37 sans table de version | idem B, invariants vérifiés | adoption |
| D. PostgreSQL vide | comme A | applique tout |
| E. migration interrompue | `schema_migrations` présente, version en retard | reprend |

L'adoption ne se décide **jamais** sur une seule colonne : elle exige que
chaque table du noyau soit présente, et que les colonnes portant les invariants
tenant-scoped de la Phase 36 le soient aussi. Une base qui échoue à ces
contrôles n'est pas adoptée — elle est refusée, avec la liste de ce qui manque.
"""

from __future__ import annotations

import os
import re
import time
from dataclasses import dataclass
from pathlib import Path

import database


SCHEMA_MIGRATIONS = "schema_migrations"
MIGRATIONS_DIRECTORY = Path(__file__).resolve().parent / "migrations"

# `0001_baseline.sql` → version 1, nom « baseline ».
_FILENAME = re.compile(r"^(\d{4})_([a-z0-9_]+)\.sql$")


class MigrationError(Exception):
    """Code stable, sans détail d'hôte ni chemin complet."""

    def __init__(self, code: str, detail: str = "") -> None:
        super().__init__(detail or code)
        self.code = code


# --------------------------------------------------------------------- dialecte

# Le DDL du noyau n'utilise que TEXT, REAL et INTEGER, sans CHECK, COLLATE ni
# DEFAULT CURRENT_TIMESTAMP — vérifié sur le schéma réel. Une seule construction
# diffère entre les deux moteurs, et elle est traduite explicitement plutôt que
# par une réécriture générale du DDL.
_AUTOINCREMENT = re.compile(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", re.I)

# Garde-fou. Si l'une de ces constructions survit au rendu, c'est qu'une
# migration a été écrite en dialecte SQLite sans qu'on s'en aperçoive — et la
# découvrir en production coûterait beaucoup plus cher qu'ici.
_SQLITE_ONLY = (
    (re.compile(r"\bAUTOINCREMENT\b", re.I), "AUTOINCREMENT"),
    (re.compile(r"\bWITHOUT\s+ROWID\b", re.I), "WITHOUT_ROWID"),
    (re.compile(r"\bPRAGMA\b", re.I), "PRAGMA"),
    (re.compile(r"\bINSERT\s+OR\s+REPLACE\b", re.I), "INSERT_OR_REPLACE"),
)


def render_ddl(ddl: str, dialect: str) -> str:
    """Adapte un DDL au moteur cible, et refuse ce qu'il ne sait pas traduire."""
    if dialect == database.SQLITE:
        return ddl
    rendered = _AUTOINCREMENT.sub(
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl
    )
    for pattern, code in _SQLITE_ONLY:
        if pattern.search(rendered):
            raise MigrationError(
                "MIGRATION_DIALECT_UNSUPPORTED",
                f"{code} cannot be rendered for PostgreSQL.",
            )
    return rendered


_CREATE_TABLE = re.compile(r"\bCREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)", re.I)
_CREATE_INDEX = re.compile(r"\bCREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s+NOT\s+EXISTS)", re.I)


def idempotent_ddl(ddl: str) -> str:
    """Le même DDL, mais qui ne se plaint pas de ce qui existe déjà.

    Sert au seul chemin d'adoption : une base historique porte une partie des
    tables et pas les autres, et il faut combler les manques avant que
    `migrate_schema` puisse faire son rattrapage de colonnes. C'est exactement
    ce que faisait l'ancien `init_db` avec ses `IF NOT EXISTS` — repris ici, au
    lieu d'être une seconde définition du schéma ailleurs.
    """
    rendered = _CREATE_TABLE.sub("CREATE TABLE IF NOT EXISTS ", ddl)
    return _CREATE_INDEX.sub(
        lambda m: f"CREATE {m.group(1) or ''}INDEX IF NOT EXISTS ", rendered
    )


def _split_statements(ddl: str) -> tuple[list[str], list[str]]:
    """Sépare les tables des index.

    L'ordre importe sur le chemin d'adoption : une base historique porte une
    table `organizations` d'avant `discovery_slug`, et `CREATE TABLE IF NOT
    EXISTS` ne la modifie pas. Créer tout de suite l'index sur cette colonne
    échouerait. On pose donc les tables, on laisse `migrate_schema` ajouter les
    colonnes, puis on pose les index.
    """
    tables, indexes = [], []
    for statement in ddl.split(";"):
        if not statement.strip():
            continue
        (tables if re.search(r"\bCREATE\s+TABLE\b", statement, re.I) else indexes).append(
            statement.strip() + ";"
        )
    return tables, indexes


def create_missing_tables(conn: database.Connection) -> None:
    """Crée les tables absentes, sans toucher à celles qui existent."""
    ddl = idempotent_ddl(render_ddl(discover()[0].sql(), conn.dialect))
    tables, _ = _split_statements(ddl)
    conn.executescript("\n".join(tables))


def create_missing_indexes(conn: database.Connection) -> None:
    """Crée les index absents. À appeler après la mise à niveau des colonnes."""
    ddl = idempotent_ddl(render_ddl(discover()[0].sql(), conn.dialect))
    _, indexes = _split_statements(ddl)
    conn.executescript("\n".join(indexes))


def create_missing(conn: database.Connection) -> None:
    """Tables puis index, dans cet ordre."""
    create_missing_tables(conn)
    create_missing_indexes(conn)


# ------------------------------------------------------------------ découverte


@dataclass(frozen=True)
class Migration:
    version: int
    name: str
    path: Path

    def sql(self) -> str:
        return self.path.read_text(encoding="utf-8")

    def apply(self, conn: database.Connection) -> None:
        conn.executescript(render_ddl(self.sql(), conn.dialect))


def discover() -> tuple[Migration, ...]:
    """Les migrations présentes sur disque, triées par version.

    L'ordre vient du numéro de fichier, jamais de l'ordre du système de
    fichiers : deux machines listeraient un répertoire différemment, et une
    migration appliquée dans le désordre est une base cassée.
    """
    if not MIGRATIONS_DIRECTORY.is_dir():
        raise MigrationError("MIGRATIONS_DIRECTORY_MISSING")
    found: dict[int, Migration] = {}
    for entry in sorted(MIGRATIONS_DIRECTORY.iterdir()):
        if not entry.is_file() or entry.suffix != ".sql":
            continue
        matched = _FILENAME.match(entry.name)
        if not matched:
            raise MigrationError(
                "MIGRATION_FILENAME_INVALID",
                f"{entry.name} does not match NNNN_name.sql",
            )
        version = int(matched.group(1))
        if version in found:
            raise MigrationError("MIGRATION_VERSION_DUPLICATE", f"version {version}")
        found[version] = Migration(version, matched.group(2), entry)
    if not found:
        raise MigrationError("MIGRATIONS_EMPTY")
    return tuple(found[version] for version in sorted(found))


def latest_version() -> int:
    return max(migration.version for migration in discover())


# --------------------------------------------------------------------- noyau

# Tables du noyau. Leur présence tranche entre « base vide » et « base à
# adopter ». Le noyau, et non toutes les tables : une base historique peut
# légitimement manquer une table ajoutée tardivement, et ce sont les migrations
# qui la lui apporteront.
CORE_TABLES = (
    "organizations",
    "users",
    "tokens",
    "federated_identities",
    "admin_sessions",
    "admin_audit_log",
)

# Colonnes portant les invariants tenant-scoped établis en Phase 36. Une base
# qui ne les a pas n'est pas au schéma de la Phase 37, quels que soient ses
# noms de tables.
REQUIRED_COLUMNS = {
    "users": ("user_id", "organization_id", "security_role", "normalized_email"),
    "federated_identities": ("user_id", "organization_id", "external_issuer"),
    "admin_audit_log": ("organization_id", "actor_user_id", "request_id"),
    "organizations": ("id", "slug", "display_name"),
}


def _ensure_version_table(conn: database.Connection) -> None:
    conn.executescript(
        f"""
        CREATE TABLE IF NOT EXISTS {SCHEMA_MIGRATIONS}(
            version INTEGER PRIMARY KEY,
            name TEXT NOT NULL,
            applied_at REAL NOT NULL
        );
        """
    )


def applied_versions(conn: database.Connection) -> set[int]:
    if not conn.table_exists(SCHEMA_MIGRATIONS):
        return set()
    rows = conn.execute(f"SELECT version FROM {SCHEMA_MIGRATIONS}").fetchall()
    return {int(row[0]) for row in rows}


def _core_present(conn: database.Connection) -> bool:
    return all(conn.table_exists(table) for table in CORE_TABLES)


def adoption_gaps(conn: database.Connection) -> list[str]:
    """Ce qui manque pour qu'une base historique soit adoptable.

    Liste vide = adoptable. Tables **et** colonnes : un nom de table ne prouve
    pas que la base porte les invariants de la Phase 36.
    """
    gaps: list[str] = []
    for table in CORE_TABLES:
        if not conn.table_exists(table):
            gaps.append(f"table:{table}")
    for table, columns in REQUIRED_COLUMNS.items():
        if not conn.table_exists(table):
            continue
        present = set(conn.columns(table))
        gaps.extend(f"column:{table}.{column}" for column in columns if column not in present)
    return gaps


def status(db: database.Database) -> dict:
    """État du schéma. Lecture seule, aucun effet de bord."""
    migrations = discover()
    latest = max(migration.version for migration in migrations)
    with db.connect() as conn:
        versioned = conn.table_exists(SCHEMA_MIGRATIONS)
        applied = applied_versions(conn)
        core = _core_present(conn)
        gaps = [] if versioned else adoption_gaps(conn)
    current = max(applied) if applied else 0
    if versioned:
        state = "current" if current == latest else ("behind" if current < latest else "ahead")
    elif core:
        state = "adoptable" if not gaps else "unrecognized"
    else:
        state = "empty"
    return {
        "dialect": db.dialect,
        "versioned": versioned,
        "current_version": current,
        "latest_version": latest,
        "applied": sorted(applied),
        "pending": sorted(m.version for m in migrations if m.version not in applied),
        "state": state,
        "adoption_gaps": gaps,
    }


def adopt(db: database.Database) -> dict:
    """Déclare une base historique conforme à la baseline, sans rien rejouer.

    Rejouer la baseline sur une base qui porte déjà les tables échouerait, ou
    pire, réussirait à moitié. L'adoption vérifie, puis déclare.
    """
    baseline = discover()[0]
    with db.connect() as conn:
        if conn.table_exists(SCHEMA_MIGRATIONS):
            raise MigrationError("MIGRATION_ALREADY_VERSIONED")
        if not _core_present(conn):
            raise MigrationError("MIGRATION_NOTHING_TO_ADOPT")
        gaps = adoption_gaps(conn)
        if gaps:
            raise MigrationError(
                "MIGRATION_ADOPTION_REFUSED", "Missing: " + ", ".join(sorted(gaps))
            )
        _ensure_version_table(conn)
        conn.execute(
            f"INSERT INTO {SCHEMA_MIGRATIONS}(version, name, applied_at) VALUES (?,?,?)",
            (baseline.version, baseline.name, time.time()),
        )
    return {"adopted": baseline.version}


def migrate(db: database.Database, *, allow_adoption: bool = True) -> dict:
    """Amène la base au dernier schéma. Idempotent.

    Chaque migration s'exécute dans sa propre transaction, avec l'écriture de sa
    version : un échec n'avance pas la version, ne laisse aucun état déclaré
    réussi, et arrête la suite. Une version marquée appliquée alors que le DDL
    ne l'est pas rendrait la base indiagnosticable.
    """
    migrations = discover()
    with db.connect() as conn:
        versioned = conn.table_exists(SCHEMA_MIGRATIONS)
        core = _core_present(conn)
    if not versioned and core:
        if not allow_adoption:
            raise MigrationError("MIGRATION_ADOPTION_REQUIRED")
        adopt(db)

    applied: list[int] = []
    for migration in migrations:
        with db.connect() as conn:
            _ensure_version_table(conn)
            if migration.version in applied_versions(conn):
                continue
            # Transaction ouverte explicitement. Le module `sqlite3` n'en ouvre
            # pas avant du DDL — seulement avant un INSERT, un UPDATE ou un
            # DELETE. Sans ce `BEGIN`, un `CREATE TABLE` s'auto-validerait, et
            # une migration qui echoue a sa troisieme instruction laisserait
            # les deux premieres en place : exactement l'etat qu'un systeme de
            # migrations existe pour rendre impossible.
            conn.begin_immediate()
            migration.apply(conn)
            conn.execute(
                f"INSERT INTO {SCHEMA_MIGRATIONS}(version, name, applied_at) VALUES (?,?,?)",
                (migration.version, migration.name, time.time()),
            )
        applied.append(migration.version)
    return {"applied": applied, "version": max(m.version for m in migrations)}


# ------------------------------------------------------------------ démarrage


def check_startup(db: database.Database) -> None:
    """Refuse de démarrer sur une base qui n'est pas au bon schéma.

    Le service ne migre jamais tout seul : une migration au démarrage se
    déclenche au pire moment, sur le premier processus qui redémarre, sans que
    personne ne l'ait demandée.
    """
    state = status(db)["state"]
    if state == "ahead":
        raise MigrationError("DATABASE_SCHEMA_TOO_NEW")
    if state != "current":
        raise MigrationError("DATABASE_MIGRATION_REQUIRED")


def ensure_schema(url: str | None = None) -> dict:
    """Applique les migrations. **Destiné aux tests et au développement.**

    Existe pour que les tests obtiennent un schéma sans que l'import d'un module
    en produise un. La différence n'est pas cosmétique : c'est un appel visible
    dans le test, au lieu d'un effet de bord invisible dans un import.
    """
    db = database.Database(url or database.configured_url())
    try:
        return migrate(db)
    finally:
        db.close()


def main(argv: list[str] | None = None) -> int:
    """`python -m migrations <status|migrate|adopt|check>`."""
    import argparse
    import json
    import sys

    parser = argparse.ArgumentParser(prog="python -m migrations")
    parser.add_argument("command", choices=("migrate", "status", "check", "adopt"))
    parser.add_argument("--url", default=None, help="overrides NOVA_DATABASE_URL")
    arguments = parser.parse_args(argv)

    db = database.Database(arguments.url or database.configured_url())
    try:
        if arguments.command == "status":
            print(json.dumps(status(db), indent=2))
        elif arguments.command == "migrate":
            print(json.dumps(migrate(db), indent=2))
        elif arguments.command == "adopt":
            print(json.dumps(adopt(db), indent=2))
        else:
            check_startup(db)
            print(json.dumps({"state": "current"}))
    except MigrationError as error:
        print(json.dumps({"error": error.code, "detail": str(error)}), file=sys.stderr)
        return 1
    finally:
        db.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
