"""Le moteur de migrations : ce qu'il applique, adopte, et refuse."""

import os
import sqlite3
import tempfile
import unittest
import uuid
from pathlib import Path

import database
import migrations


POSTGRES_URL = os.getenv("NOVA_TEST_POSTGRES_URL", "").strip()


def temporary_sqlite(directory: tempfile.TemporaryDirectory) -> str:
    path = os.path.join(directory.name, f"m-{uuid.uuid4().hex}.db").replace("\\", "/")
    return "sqlite:///" + path


class DiscoveryTests(unittest.TestCase):
    def test_migrations_are_discovered_in_numeric_order(self):
        found = migrations.discover()
        self.assertTrue(found)
        versions = [migration.version for migration in found]
        self.assertEqual(versions, sorted(versions))
        self.assertEqual(versions[0], 1)

    def test_the_baseline_carries_the_whole_core(self):
        sql = migrations.discover()[0].sql()
        for table in migrations.CORE_TABLES:
            self.assertIn(f"CREATE TABLE {table}(", sql, table)

    def test_the_baseline_is_free_of_constructs_postgres_cannot_take(self):
        # Rendu pour PostgreSQL : si une construction propre a SQLite y
        # survivait, `render_ddl` leverait plutot que de la transmettre.
        rendered = migrations.render_ddl(
            migrations.discover()[0].sql(), database.POSTGRESQL
        )
        self.assertNotIn("AUTOINCREMENT", rendered.upper())
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", rendered)

    def test_a_ddl_that_cannot_be_rendered_is_refused(self):
        for ddl in (
            "CREATE TABLE t(id INTEGER PRIMARY KEY AUTOINCREMENT, x TEXT); PRAGMA foo;",
            "INSERT OR REPLACE INTO t VALUES (1);",
            "CREATE TABLE t(a TEXT) WITHOUT ROWID;",
        ):
            with self.assertRaises(migrations.MigrationError, msg=ddl):
                migrations.render_ddl(ddl, database.POSTGRESQL)


class EngineMigrationTests:
    """Meme contrat sous les deux moteurs."""

    def url(self) -> str:
        raise NotImplementedError

    def test_an_empty_database_reaches_the_latest_schema(self):
        db = database.Database(self.url())
        try:
            self.assertEqual(migrations.status(db)["state"], "empty")
            applied = migrations.migrate(db)
            # Derive du disque, pas d'une liste ecrite ici : figer `[1]` faisait
            # echouer ce test a chaque migration ajoutee, pour une raison sans
            # rapport avec ce qu'il verifie.
            self.assertEqual(
                applied["applied"],
                [migration.version for migration in migrations.discover()],
            )
            state = migrations.status(db)
            self.assertEqual(state["state"], "current")
            self.assertEqual(state["current_version"], state["latest_version"])
            self.assertEqual(state["pending"], [])
        finally:
            db.close()

    def test_migrating_twice_changes_nothing(self):
        db = database.Database(self.url())
        try:
            migrations.migrate(db)
            second = migrations.migrate(db)
            self.assertEqual(second["applied"], [])
            self.assertEqual(migrations.status(db)["state"], "current")
        finally:
            db.close()

    def test_startup_is_refused_until_the_schema_is_applied(self):
        db = database.Database(self.url())
        try:
            with self.assertRaises(migrations.MigrationError) as raised:
                migrations.check_startup(db)
            self.assertEqual(raised.exception.code, "DATABASE_MIGRATION_REQUIRED")
            migrations.migrate(db)
            migrations.check_startup(db)
        finally:
            db.close()

    def test_a_schema_from_the_future_is_refused_never_downgraded(self):
        db = database.Database(self.url())
        try:
            migrations.migrate(db)
            with db.connect() as conn:
                conn.execute(
                    "INSERT INTO schema_migrations(version, name, applied_at) "
                    "VALUES (?,?,?)",
                    (9999, "from_the_future", 0.0),
                )
            self.assertEqual(migrations.status(db)["state"], "ahead")
            with self.assertRaises(migrations.MigrationError) as raised:
                migrations.check_startup(db)
            self.assertEqual(raised.exception.code, "DATABASE_SCHEMA_TOO_NEW")
            # Et rien n'a ete supprime pour « revenir » a la version connue.
            with db.connect() as conn:
                versions = migrations.applied_versions(conn)
            self.assertIn(9999, versions)
        finally:
            db.close()

    def test_a_failing_migration_rolls_back_and_stops_the_run(self):
        """Une migration cassee ne doit rien laisser derriere elle."""
        db = database.Database(self.url())
        directory = migrations.MIGRATIONS_DIRECTORY
        broken = directory / "9998_deliberately_broken.sql"
        follower = directory / "9999_must_not_run.sql"
        broken.write_text(
            "CREATE TABLE broken_probe(id TEXT);\n"
            "CREATE TABLE broken_probe(id TEXT);\n",
            encoding="utf-8",
        )
        follower.write_text("CREATE TABLE never_created(id TEXT);\n", encoding="utf-8")
        try:
            with self.assertRaises(Exception):
                migrations.migrate(db)
            with db.connect() as conn:
                applied = migrations.applied_versions(conn)
                # La version cassee n'est pas marquee appliquee...
                self.assertNotIn(9998, applied)
                # ...la suivante n'a pas ete tentee...
                self.assertNotIn(9999, applied)
                self.assertFalse(conn.table_exists("never_created"))
                # ...et la table a moitie creee a ete annulee.
                self.assertFalse(conn.table_exists("broken_probe"))
        finally:
            broken.unlink(missing_ok=True)
            follower.unlink(missing_ok=True)
            db.close()

    def test_the_version_table_records_what_was_applied(self):
        db = database.Database(self.url())
        try:
            migrations.migrate(db)
            with db.connect() as conn:
                row = conn.execute(
                    "SELECT version, name, applied_at FROM schema_migrations "
                    "WHERE version=?",
                    (1,),
                ).fetchone()
            self.assertEqual(row["version"], 1)
            self.assertEqual(row["name"], "baseline")
            self.assertGreater(row["applied_at"], 0)
        finally:
            db.close()


class SqliteMigrationTests(EngineMigrationTests, unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory()

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def url(self) -> str:
        return temporary_sqlite(self.directory)


@unittest.skipUnless(POSTGRES_URL, "NOVA_TEST_POSTGRES_URL is not set")
class PostgresMigrationTests(EngineMigrationTests, unittest.TestCase):
    def url(self) -> str:
        # Un schema PostgreSQL neuf par scenario : deux scenarios qui
        # partageraient des tables se pollueraient.
        import psycopg

        schema = "m" + uuid.uuid4().hex[:12]
        with psycopg.connect(POSTGRES_URL, autocommit=True) as setup:
            setup.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        self.addCleanup(self._drop, schema)
        return f"{POSTGRES_URL}?options=-csearch_path%3D{schema}"

    @staticmethod
    def _drop(schema: str) -> None:
        import psycopg

        with psycopg.connect(POSTGRES_URL, autocommit=True) as cleanup:
            cleanup.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')


class LegacyAdoptionTests(unittest.TestCase):
    """Une base historique est adoptee, jamais rejouee."""

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)

    def _phase37_database(self) -> str:
        """Une base au schema de la Phase 37, sans table de version.

        La baseline seule, pas le schema courant : une base historique s'est
        arretee la ou le versionnement a commence. Y appliquer d'abord les
        migrations posterieures aurait decrit une situation qui n'existe pas —
        elles ne sont livrees qu'avec le moteur qui enregistre les versions.
        """
        url = temporary_sqlite(self.directory)
        db = database.Database(url)
        baseline = migrations.discover()[0]
        with db.connect() as conn:
            migrations._ensure_version_table(conn)
            baseline.apply(conn)
        with db.connect() as conn:
            conn.executescript("DROP TABLE schema_migrations;")
            conn.execute(
                "INSERT INTO organizations(id, slug, display_name, created_at) "
                "VALUES (?,?,?,?)",
                ("org-legacy", "legacy", "Legacy", 1.0),
            )
        db.close()
        return url

    def test_a_phase37_database_is_adopted_without_replaying_anything(self):
        url = self._phase37_database()
        db = database.Database(url)
        try:
            state = migrations.status(db)
            self.assertEqual(state["state"], "adoptable")
            self.assertEqual(state["adoption_gaps"], [])

            migrations.migrate(db)

            self.assertEqual(migrations.status(db)["state"], "current")
            with db.connect() as conn:
                # Aucune donnee perdue : rejouer la baseline aurait echoue ou,
                # pire, reussi a moitie.
                kept = conn.execute(
                    "SELECT display_name FROM organizations WHERE id=?", ("org-legacy",)
                ).fetchone()
                self.assertEqual(kept["display_name"], "Legacy")
                self.assertEqual(
                    migrations.applied_versions(conn),
                    {migration.version for migration in migrations.discover()},
                )
        finally:
            db.close()

    def test_adoption_is_refused_when_an_invariant_column_is_missing(self):
        """Une base qui n'a pas les invariants Phase 36 n'est pas adoptable."""
        url = temporary_sqlite(self.directory)
        path = url[len("sqlite:///") :]
        conn = sqlite3.connect(path)
        # Les noms de tables du noyau, mais sans les colonnes qui portent le
        # cloisonnement par organisation.
        conn.executescript(
            """
            CREATE TABLE organizations(id TEXT PRIMARY KEY);
            CREATE TABLE users(email TEXT PRIMARY KEY);
            CREATE TABLE tokens(token TEXT PRIMARY KEY);
            CREATE TABLE federated_identities(provider TEXT);
            CREATE TABLE admin_sessions(id TEXT PRIMARY KEY);
            CREATE TABLE admin_audit_log(id TEXT PRIMARY KEY);
            """
        )
        conn.commit()
        conn.close()

        db = database.Database(url)
        try:
            state = migrations.status(db)
            self.assertEqual(state["state"], "unrecognized")
            self.assertTrue(state["adoption_gaps"])
            self.assertIn("column:users.user_id", state["adoption_gaps"])

            with self.assertRaises(migrations.MigrationError) as raised:
                migrations.adopt(db)
            self.assertEqual(raised.exception.code, "MIGRATION_ADOPTION_REFUSED")
            # Le message dit ce qui manque, sans exposer de chemin.
            self.assertIn("users.user_id", str(raised.exception))
        finally:
            db.close()

    def test_adopting_an_already_versioned_database_is_refused(self):
        url = temporary_sqlite(self.directory)
        db = database.Database(url)
        try:
            migrations.migrate(db)
            with self.assertRaises(migrations.MigrationError) as raised:
                migrations.adopt(db)
            self.assertEqual(raised.exception.code, "MIGRATION_ALREADY_VERSIONED")
        finally:
            db.close()

    def test_adopting_an_empty_database_is_refused(self):
        db = database.Database(temporary_sqlite(self.directory))
        try:
            with self.assertRaises(migrations.MigrationError) as raised:
                migrations.adopt(db)
            self.assertEqual(raised.exception.code, "MIGRATION_NOTHING_TO_ADOPT")
        finally:
            db.close()


class ImportSideEffectTests(unittest.TestCase):
    """Importer `main` ne doit migrer aucune base."""

    def test_importing_main_performs_no_migration(self):
        import json
        import subprocess
        import sys
        import textwrap

        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        path = os.path.join(directory.name, "import-probe.db")

        program = textwrap.dedent(
            """
            import json, os, sqlite3, sys

            sys.path.insert(0, sys.argv[2])
            path = sys.argv[1]
            os.environ["NOVA_DB"] = path
            os.environ.setdefault("NOVA_DOMAINS", "example.com")
            os.environ.setdefault("NOVA_ORGANIZATION_NAME", "Probe")

            def tables():
                if not os.path.exists(path):
                    return []
                conn = sqlite3.connect(path)
                try:
                    return sorted(
                        row[0] for row in conn.execute(
                            "SELECT name FROM sqlite_master WHERE type='table'"
                        )
                    )
                finally:
                    conn.close()

            before = tables()
            import main
            after = tables()
            main.init_db()
            explicit = tables()
            print(json.dumps({"before": before, "after": after,
                              "explicit": len(explicit)}))
            """
        )
        script = os.path.join(directory.name, "probe.py")
        with open(script, "w", encoding="utf-8") as handle:
            handle.write(program)

        completed = subprocess.run(
            [sys.executable, script, path, os.path.dirname(os.path.abspath(__file__))],
            cwd=os.path.dirname(os.path.abspath(__file__)),
            capture_output=True,
            text=True,
            timeout=300,
        )
        self.assertEqual(completed.returncode, 0, completed.stderr[-3000:])
        result = json.loads(completed.stdout.strip().splitlines()[-1])

        # C'est l'assertion centrale de cette continuation : l'import ne cree
        # rien. Deux bases de production ont ete migrees par un import ;
        # ce test est ce qui empeche la troisieme.
        self.assertEqual(result["before"], [])
        self.assertEqual(result["after"], [], "importing main must not migrate")
        self.assertGreater(result["explicit"], 20, "init_db must still build the schema")


    def test_every_test_module_that_uses_main_asks_for_its_schema(self):
        """Le corollaire du test precedent, cote suite.

        Si l'import ne migre rien, alors chaque module de test qui se sert du
        schema doit l'appeler lui-meme. `test_deployment.py` ne le faisait pas :
        il passait quand meme, parce qu'un autre module importe `main` avant lui
        et que le premier `NOVA_DB` pose vaut pour tous -- les tables existaient,
        creees par quelqu'un d'autre. Lance seul, il echouait dix-huit fois sur
        « no such table: deployment_profiles ».

        Un test dont le resultat depend de ses voisins ne verifie pas ce qu'il
        annonce, et l'ordre qui le sauve n'est garanti par rien.
        """
        import ast

        root = Path(os.path.abspath(__file__)).parent
        oublis = []
        for module in sorted(root.glob("test_*.py")):
            source = module.read_text(encoding="utf-8")
            arbre = ast.parse(source)
            # Un import au niveau du module seulement : `test_production_database`
            # importe `main` dans un sous-processus, et n'a aucun schema a batir.
            importe = any(
                (isinstance(noeud, ast.Import)
                 and any(nom.name == "main" for nom in noeud.names))
                or (isinstance(noeud, ast.ImportFrom) and noeud.module == "main")
                for noeud in arbre.body
            )
            if importe and "init_db" not in source:
                oublis.append(module.name)
        self.assertEqual(
            oublis, [],
            "ces modules empruntent le schema d'un autre au lieu de le demander",
        )

